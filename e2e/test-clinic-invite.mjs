import fs from 'node:fs';
import { launch, BASE, shot, SHOTS } from './harness.mjs';
fs.mkdirSync(SHOTS, { recursive: true });
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${ok ? '' : '  ← ' + x}`); };

const { browser, page, posts, errors } = await launch();
await page.goto(`${BASE}/client/farm/medical`, { waitUntil: 'networkidle' });
await page.waitForTimeout(600);
await page.getByRole('button', { name: 'Connect a clinic' }).first().click();
await page.getByPlaceholder('Clinic name or town').fill('we');
await page.waitForTimeout(900);
check('lists the real clinic by name', await page.getByText('Westlands Paws Vet Clinic').first().isVisible());
check('explains it cannot open records yet', await page.getByText(/cannot open farm records yet/).isVisible());
check('no more bare "1 other clinic matches"', (await page.getByText(/other clinic matches/).count()) === 0);
await shot(page, '10-invite-list');
const before = posts.length;
await page.getByRole('button', { name: 'Ask to join' }).click();
await page.waitForTimeout(700);
const p = posts.slice(before).find((x) => /clinic-invites$/.test(x.path));
check('POSTs the ask for that clinic', p?.body?.clinicId === 'c9', JSON.stringify(posts.slice(before)));
check('button becomes "Asked"', await page.getByText('Asked', { exact: true }).first().isVisible());
await shot(page, '11-invite-asked');
await page.keyboard.press('Escape');
await page.getByRole('button', { name: /close/i }).first().click().catch(() => {});
await page.waitForTimeout(500);
await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(600);
check('Medical card says who we are waiting on', await page.getByText(/Waiting on Westlands Paws Vet Clinic/).isVisible());
await shot(page, '12-waiting-card');
const real = errors.filter((e) => !/EventSource|text\/event-stream/.test(e));
check('no console errors', real.length === 0, real.slice(0, 3).join(' | '));
console.log(`\n${pass} passed, ${fail} failed`);
await browser.close();
process.exit(fail ? 1 : 0);
