import fs from 'node:fs';
import { launch, BASE, shot, SHOTS } from './harness.mjs';
fs.mkdirSync(SHOTS, { recursive: true });
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${ok ? '' : '  ← ' + x}`); };
const { browser, page, posts, errors, reminders } = await launch();
await page.goto(`${BASE}/client/farm`, { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
const card = page.getByTestId('farm-reminders');
check('"Coming up" card is on the farm home', await card.isVisible());
const t = await card.innerText();
check('shows the due date reminder', /Bika is due/.test(t) && /in 5 days/.test(t), t);
check('overdue dry-off is flagged', /Dry off Bika/.test(t) && /3 days ago/.test(t), t);
check('clinic advice is labelled with the clinic', /Book a pre-calving check/.test(t) && /from Westlands Paws/.test(t), t);
check('advice note is shown', /Bring her weight record/.test(t), t);
await shot(page, '40-reminders');
await card.getByRole('button', { name: 'Done' }).first().click(); await page.waitForTimeout(500);
const p = [...posts].reverse().find((x) => /farm-reminders\/r1$/.test(x.path));
check('Done PATCHes status DONE', p?.body?.status === 'DONE', JSON.stringify(posts.slice(-2)));
check('it leaves the list', !/Bika is due/.test(await card.innerText()));
await card.getByRole('button', { name: 'Dismiss' }).first().click(); await page.waitForTimeout(500);
check('Dismiss PATCHes status DISMISSED', reminders.find((r) => r.id === 'r2').status === 'DISMISSED');
const real = errors.filter((e) => !/EventSource|text\/event-stream/.test(e));
check('no console errors', real.length === 0, real.slice(0, 3).join(' | '));
console.log(`\n${pass} passed, ${fail} failed`);
await browser.close();
process.exit(fail ? 1 : 0);
